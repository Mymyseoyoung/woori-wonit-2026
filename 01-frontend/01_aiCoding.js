// 두 수를 더하는 함수를 작성해줘. ( 이미 만들어진 코드에는 새로운 프롬프팅이 적용 안됨 ! )
function addNumbers(num1, num2) {
    return num1 + num2;
}

// 두 수를 빼는 함수 
//tab으로 선택, esc로 자동완성 취소
//변경할 영역을 드래그 해서 선택한 후 , Ctrl + I 로 질문창을 열어서 수정 ! 
function subtract(num1, num2) {
    return num1 - num2;
}

// Ctrl + Shift + Alt + L 로 질문창을 엽니다 . 
// 질문을 이어서 연속해서 할 수 있습니다. 
